package com.spring.bioMedical.service;

import java.awt.Color;
import java.io.ByteArrayOutputStream;
import java.time.LocalDate;
import java.time.format.DateTimeFormatter;

import org.springframework.stereotype.Component;

import com.lowagie.text.Chunk;
import com.lowagie.text.Document;
import com.lowagie.text.Element;
import com.lowagie.text.Font;
import com.lowagie.text.PageSize;
import com.lowagie.text.Paragraph;
import com.lowagie.text.Phrase;
import com.lowagie.text.Rectangle;
import com.lowagie.text.pdf.PdfPCell;
import com.lowagie.text.pdf.PdfPTable;
import com.lowagie.text.pdf.PdfWriter;
import com.lowagie.text.pdf.draw.LineSeparator;
import com.spring.bioMedical.dto.PrescriptionDto;
import com.spring.bioMedical.dto.PrescriptionRequest;

/** Renders a prescription as a one-page A4 PDF. */
@Component
public class PrescriptionPdf {

	private static final Color BRAND = new Color(37, 99, 235);
	private static final Color MUTED = new Color(100, 116, 139);
	private static final DateTimeFormatter LONG_DATE = DateTimeFormatter.ofPattern("d MMMM yyyy");

	private static final Font TITLE = new Font(Font.HELVETICA, 18, Font.BOLD, BRAND);
	private static final Font HEADING = new Font(Font.HELVETICA, 11, Font.BOLD, Color.DARK_GRAY);
	private static final Font BODY = new Font(Font.HELVETICA, 10, Font.NORMAL, Color.BLACK);
	private static final Font SMALL = new Font(Font.HELVETICA, 8, Font.NORMAL, MUTED);
	private static final Font CELL_HEAD = new Font(Font.HELVETICA, 9, Font.BOLD, Color.WHITE);

	public byte[] render(PrescriptionDto p) {
		ByteArrayOutputStream out = new ByteArrayOutputStream();
		Document doc = new Document(PageSize.A4, 48, 48, 48, 48);
		PdfWriter.getInstance(doc, out);
		doc.addTitle("Prescription - " + p.patientName());
		doc.addCreator("E-Medical");
		doc.open();

		doc.add(new Paragraph("E-Medical", TITLE));
		doc.add(new Paragraph("Prescription and visit summary", SMALL));
		doc.add(new Chunk(new LineSeparator(1f, 100f, BRAND, Element.ALIGN_CENTER, -4)));
		doc.add(spacer());

		PdfPTable who = new PdfPTable(2);
		who.setWidthPercentage(100);
		who.addCell(info("Patient", p.patientName() + "\n" + p.patientEmail()));
		who.addCell(info("Doctor", p.doctorName() + (p.department() == null ? "" : "\n" + p.department())));
		who.addCell(info("Visit", formatDate(p.visitDate()) + " at " + p.visitTime()));
		who.addCell(info("Follow-up", p.followUpDate() == null ? "Not needed" : formatDate(p.followUpDate())));
		doc.add(who);
		doc.add(spacer());

		doc.add(new Paragraph("Diagnosis", HEADING));
		doc.add(new Paragraph(p.diagnosis(), BODY));
		doc.add(spacer());

		doc.add(new Paragraph("Medicines", HEADING));
		if (p.medicines().isEmpty()) {
			doc.add(new Paragraph("No medicines prescribed.", BODY));
		} else {
			PdfPTable meds = new PdfPTable(new float[] { 4, 2, 4, 2 });
			meds.setWidthPercentage(100);
			meds.setSpacingBefore(6);
			for (String h : new String[] { "Medicine", "Dosage", "How often", "Days" }) {
				PdfPCell c = new PdfPCell(new Phrase(h, CELL_HEAD));
				c.setBackgroundColor(BRAND);
				c.setPadding(6);
				c.setBorderColor(BRAND);
				meds.addCell(c);
			}
			for (PrescriptionRequest.MedicineLine m : p.medicines()) {
				meds.addCell(cell(m.name()));
				meds.addCell(cell(m.dosage()));
				meds.addCell(cell(m.frequency()));
				meds.addCell(cell(m.durationDays() == null ? "" : String.valueOf(m.durationDays())));
			}
			doc.add(meds);
		}
		doc.add(spacer());

		if (p.notes() != null) {
			doc.add(new Paragraph("Advice", HEADING));
			doc.add(new Paragraph(p.notes(), BODY));
			doc.add(spacer());
		}

		doc.add(new Paragraph("Issued by " + p.doctorName() + " through E-Medical. Last updated "
				+ (p.updatedAt() == null ? "" : p.updatedAt().replace('T', ' ')) + ".", SMALL));
		doc.add(new Paragraph("This is a demo document generated by a portfolio project, not a real medical record.", SMALL));
		doc.close();
		return out.toByteArray();
	}

	private static PdfPCell info(String label, String value) {
		PdfPCell c = new PdfPCell();
		c.setBorder(Rectangle.NO_BORDER);
		c.setPaddingBottom(8);
		c.addElement(new Paragraph(label.toUpperCase(), SMALL));
		c.addElement(new Paragraph(value, BODY));
		return c;
	}

	private static PdfPCell cell(String value) {
		PdfPCell c = new PdfPCell(new Phrase(value == null ? "" : value, BODY));
		c.setPadding(6);
		c.setBorderColor(new Color(226, 232, 240));
		return c;
	}

	private static Paragraph spacer() {
		Paragraph p = new Paragraph(" ", BODY);
		p.setSpacingAfter(2);
		return p;
	}

	private static String formatDate(String iso) {
		try {
			return LocalDate.parse(iso).format(LONG_DATE);
		} catch (Exception e) {
			return iso;
		}
	}
}
